/** Glif pengganti untuk karakter tak dikenal: kotak kecil. */
const FALLBACK_RAW = '...../.###./.#.#./.#.#./.#.#./.###./.....'

function parse(raw: string): readonly (readonly boolean[])[] {
  return raw.split('/').map((row) => Array.from(row, (ch) => ch === '#'))
}

const GLYPHS: ReadonlyMap<string, readonly (readonly boolean[])[]> = new Map(
  Object.entries(RAW).map(([ch, raw]) => [ch, parse(raw)]),
)
const FALLBACK_GLYPH = parse(FALLBACK_RAW)

/** True bila karakter punya glif sendiri (spasi dihitung dikenal). */
export function hasGlyph(ch: string): boolean {
  return ch === ' ' || GLYPHS.has(ch)
}

function glyphFor(ch: string): readonly (readonly boolean[])[] {
  return GLYPHS.get(ch) ?? FALLBACK_GLYPH
}

function advance(ch: string): number {
  return (ch === ' ' ? SPACE_W : GLYPH_W) + LETTER_SPACING
}

export function measurePixelText(text: string): { w: number; h: number } {
  const chars = Array.from(text)
  if (chars.length === 0) return { w: 0, h: GLYPH_H }
  let w = 0
  for (const ch of chars) w += advance(ch)
  return { w: w - LETTER_SPACING, h: GLYPH_H }
}

export function paintPixelText(text: string, color: string): PixelGrid {
  const { w, h } = measurePixelText(text)
  const cells: (string | null)[] = new Array(w * h).fill(null)
  let x0 = 0
  for (const ch of Array.from(text)) {
    if (ch !== ' ') {
      const glyph = glyphFor(ch)
      for (let y = 0; y < GLYPH_H; y++) {
        for (let x = 0; x < GLYPH_W; x++) {
          if (glyph[y]?.[x]) cells[y * w + x0 + x] = color
        }
      }
    }
    x0 += advance(ch)
  }
  return { width: w, height: h, cells }
}
